#!/usr/bin/env node
import fs from 'node:fs';

let passed = 0;
let failed = 0;
function check(name, condition, detail = '') {
  if (condition) passed++; else failed++;
  console.log(`${condition ? 'PASS' : 'FAIL'}  ${name}${detail ? ` — ${detail}` : ''}`);
}

const source = fs.readFileSync(new URL('../_worker.js', import.meta.url), 'utf8');
const workerModule = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const worker = workerModule.default;

async function a2a(body, version = '1.0', env = {}) {
  const response = await worker.fetch(new Request('https://3webobs.com/a2a', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'A2A-Version': version },
    body: JSON.stringify(body)
  }), env, {});
  return { status: response.status, body: await response.json() };
}

console.log('\n[A2A strict errors]');
{
  const missingMethod = await a2a({ jsonrpc: '2.0', id: 1 });
  check('missing method returns Invalid Request', missingMethod.body.error?.code === -32600,
    String(missingMethod.body.error?.code));

  const wrongVersion = await a2a({ jsonrpc: '2.0', id: 2, method: 'SendMessage', params: {} }, '9.9');
  const versionData = wrongVersion.body.error?.data;
  check('unsupported version returns -32009', wrongVersion.body.error?.code === -32009,
    String(wrongVersion.body.error?.code));
  check('A2A error.data is a typed array', Array.isArray(versionData) &&
    typeof versionData[0]?.['@type'] === 'string', JSON.stringify(versionData));

  const taskMissing = await a2a({ jsonrpc: '2.0', id: 3, method: 'GetTask', params: { id: 'missing' } },
    '1.0', { RATE_KV: { get: async () => null } });
  check('missing task returns -32001', taskMissing.body.error?.code === -32001,
    String(taskMissing.body.error?.code));
  check('TaskNotFound details are typed', Array.isArray(taskMissing.body.error?.data) &&
    !!taskMissing.body.error.data[0]?.['@type']);
}

console.log('\n[Fallback and DOM integrity]');
{
  const html = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
  check('audit failure exits before score generation', /showAuditUnavailable\(url,e\.message\);\s*return;/.test(html));
  check('report URL is escaped before HTML insertion', html.includes('<div class="sh-url">${esc(d.url)}</div>'));
  check('share recipient is escaped before HTML insertion', html.includes('Report copied to clipboard · To: ${esc(val)}'));
  check('unavailable state explicitly creates no score', html.includes('No score, signal verdict, synthesis or action plan has been created'));
  check('/audit uses a real dependency error', /upstreamStatus: ev\.status \}, 424\)/.test(source));
}

console.log('\n[AI declaration consistency]');
{
  const ai = JSON.parse(fs.readFileSync(new URL('../ai.json', import.meta.url), 'utf8'));
  const governance = JSON.parse(fs.readFileSync(new URL('../governance.json', import.meta.url), 'utf8'));
  const act = fs.readFileSync(new URL('../ai-act.html', import.meta.url), 'utf8');
  check('ai.json declares no language model', ai.ai_usage?.narrative_summary?.uses_language_model === false &&
    ai.ai_usage?.audit_data_sent_to_llm_provider === false);
  check('governance declares no language model', governance.ai_usage?.narrative_summary?.language_model_may_be_used === false);
  check('AI Act page no longer claims model-generated synthesis',
    !/general-purpose language model turns|generated by an AI system operating on the audit result|sent to the AI provider for synthesis/i.test(act));
}

console.log('\n[Public contracts]');
{
  const agents = fs.readFileSync(new URL('../agents.html', import.meta.url), 'utf8');
  const homepage = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
  check('A2A documentation uses result.message', /"result": \{\s*"message": \{/.test(agents));
  check('A2A Python example reads result.message', agents.includes('["result"]["message"]["parts"]'));
  check('A2A documentation publishes -32009', agents.includes('-32009 VersionNotSupportedError') && !agents.includes('-32003 VersionNotSupportedError'));
  check('JSON-LD publishes all six dimensions', homepage.includes('"name":"The six audit dimensions"') &&
    homepage.includes('"name":"A2A","description":"13 signals'));
  check('JSON-LD version matches the engine', homepage.includes('"softwareVersion":"3.6.1"') &&
    homepage.includes('"assemblyVersion":"3.6.1"'));
}

console.log(`\nResult: ${passed}/${passed + failed} passed`);
if (failed) process.exit(1);
